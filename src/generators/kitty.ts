import { PaletteFile, resolve, ansiBright } from "../lib/palette";

/**
 * Generates the kitty theme. The 16 ANSI slots are exactly those of VS Code's
 * integrated terminal and of Base24 (same roles, same ansiBright()), so an
 * `ls --color` or a `git diff` looks identical in all three places.
 *
 * Usage: copy to ~/.config/kitty/ and put `include cadenza.conf` in
 * kitty.conf (or point `kitten themes` at the file).
 */
export function generateKittyTheme(p: PaletteFile): string {
  const c = p.palette;
  const ui = (role: string) => resolve(p, "ui", role);
  const ansi = (slot: string) => resolve(p, "terminal", slot);
  const ORDER = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];

  const colors = [
    ...ORDER.map((slot, i) => `color${i}  ${ansi(slot)}`),
    ...ORDER.map((slot, i) => `color${i + 8}${i + 8 < 10 ? " " : ""} ${ansiBright(p, slot)}`),
  ].join("\n");

  return `# ${p.meta.name} — kitty
# Generated by src/generators/kitty.ts from palette/. DO NOT edit by hand.
# ${p.meta.description}

foreground              ${c.fg0}
background              ${ui("terminal-bg")}
# "none" keeps the output's colour on top of the selection, like the editor.
selection_foreground    none
selection_background    ${c.selection}

cursor                  ${ui("cursor")}
cursor_text_color       ${c.bg0}
url_color               ${ui("link")}

# Split borders: the active window gets the accent, the others fade into the background.
active_border_color     ${ui("border-active")}
inactive_border_color   ${ui("border-inactive")}
bell_border_color       ${c.warning}
visual_bell_color       none

# Flat tab bar: active tab one step up, inactive ones on the background.
tab_bar_background      ${c.bg0}
tab_bar_margin_color    ${c.bg0}
active_tab_foreground   ${c.fg0}
active_tab_background   ${c.bg2}
active_tab_font_style   bold
inactive_tab_foreground ${c.muted}
inactive_tab_background ${c.bg0}
inactive_tab_font_style normal

# Marks (kitten marks / hints)
mark1_foreground        ${c.bg0}
mark1_background        ${c.lilac}
mark2_foreground        ${c.bg0}
mark2_background        ${c.gold}
mark3_foreground        ${c.bg0}
mark3_background        ${c.jade}

# ANSI — 8 bases + 8 brights (+0.10 L in OKLCH)
${colors}
`;
}
