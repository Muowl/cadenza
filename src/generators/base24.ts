import { PaletteFile, resolve, lighten, darken, ansiBright } from "../lib/palette";

/**
 * Generates the Base24 scheme (tinted-theming ecosystem) from the source of
 * truth. Unlocks the ready-made templates for terminals, tmux, shells, rofi etc.
 *
 * Mapping decisions — where Base24 diverges from the VS Code theme, the rule
 * was "get the terminal right first":
 *
 * - base08–base0E follow the SAME tokens as the ANSI slots (roles.terminal),
 *   and base12–base17 use ansiBright(): a terminal themed via Base24 matches
 *   VS Code's integrated terminal and the kitty theme generated here.
 * - base0B (green) paints strings in base16/base24 templates, but here it's
 *   the lime of `success`: in a terminal, green means diff/ok. The editor's
 *   gold strings are already in base0A (ANSI yellow).
 * - base09 (orange) is the amber of `warning`; base0F ("deprecated") is
 *   `error`, the coral red, distinct from base08's scarlet.
 * - base06/base07 and base10/base11 are steps derived from fg0/bg0 with
 *   lighten()/darken(); almost no template uses these extremes.
 */
export function generateBase24Scheme(p: PaletteFile): string {
  const c = p.palette;
  const ansi = (slot: string) => resolve(p, "terminal", slot);
  const bright = (slot: string) => ansiBright(p, slot);

  const slots: [string, string, string][] = [
    ["base00", c.bg0, "editor background (bg0)"],
    ["base01", c.bg1, "raised surfaces, widgets (bg1)"],
    ["base02", c.selection, "text selection (selection)"],
    ["base03", c.muted, "comments (muted)"],
    ["base04", c.fg1, "secondary text (fg1)"],
    ["base05", c.fg0, "primary text (fg0)"],
    // fg0 is already light: small steps vanish in the 8-bit conversion.
    // 0.25/0.5 give a visible step without reaching pure #fff.
    ["base06", lighten(c.fg0, 0.25), "light text (fg0 lightened)"],
    ["base07", lighten(c.fg0, 0.5), "lightest white (fg0 lightened)"],
    ["base08", ansi("red"), "red — the signature (scarlet, jacket)"],
    ["base09", c.warning, "orange — amber (warning)"],
    ["base0A", ansi("yellow"), "yellow — microphone gold (gold)"],
    ["base0B", ansi("green"), "green — medallion's lime ring (success)"],
    ["base0C", ansi("cyan"), "cyan — jade earrings (jade)"],
    ["base0D", ansi("blue"), "blue — the CD's blue rim (info)"],
    ["base0E", ansi("magenta"), "magenta — medallion orchid (orchid)"],
    ["base0F", c.error, "deprecated — the coral red (error)"],
    ["base10", darken(c.bg0, 0.15), "darker background (bg0 darkened)"],
    ["base11", darken(c.bg0, 0.3), "darkest background (bg0 darkened)"],
    ["base12", bright("red"), "bright red (ANSI bright)"],
    ["base13", bright("yellow"), "bright yellow (ANSI bright)"],
    ["base14", bright("green"), "bright green (ANSI bright)"],
    ["base15", bright("cyan"), "bright cyan (ANSI bright)"],
    ["base16", bright("blue"), "bright blue (ANSI bright)"],
    ["base17", bright("magenta"), "bright magenta (ANSI bright)"],
  ];

  const lines = slots
    .map(([slot, hex, note]) => `  ${slot}: "${hex}" # ${note}`)
    .join("\n");

  return `# Generated by src/generators/base24.ts from palette/ (Cadenza).
# DO NOT edit by hand — run \`npm run build\`.
system: "base24"
name: "${p.meta.name}"
slug: "${p.meta.slug}"
author: "${p.meta.author}"
variant: "${p.meta.variant}"
palette:
${lines}
`;
}
