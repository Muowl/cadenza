import { PaletteFile, resolve, ansiBright } from "../lib/palette";

/**
 * Desktop exports (Hyprland, Waybar and anything that reads JSON:
 * quickshell, ags, eww, scripts).
 *
 * Colours ONLY, with the same names in every format, so a config written
 * against `$accent` / `@accent` switches variant by switching the included
 * file. Layout, fonts and bar modules belong to the user's config — the
 * theme doesn't decide those.
 */

/** UI roles that become colour names on the desktop, besides the palette tokens. */
const DESKTOP_ROLES = [
  "accent",
  "cursor",
  "link",
  "border-active",
  "border-inactive",
  "urgent",
] as const;

/** Name safe for hyprlang and GTK CSS: hyphen becomes underscore. */
const safeName = (s: string) => s.replace(/-/g, "_");

/** Every exported colour, in order: palette, then UI roles. */
function colors(p: PaletteFile): [string, string][] {
  return [
    ...Object.entries(p.palette).map(([k, v]) => [safeName(k), v] as [string, string]),
    ...DESKTOP_ROLES.map((r) => [safeName(r), resolve(p, "ui", r)] as [string, string]),
  ];
}

const bare = (hex: string) => hex.slice(1);

/**
 * Hyprland (hyprlang). `$name = rgb(rrggbb)` for direct use and
 * `$nameAlpha = rrggbb` to compose transparency: `rgba($bg0Alphacc)`.
 * Usage: `source = ~/.config/hypr/cadenza.conf` in hyprland.conf.
 */
export function generateHyprland(p: PaletteFile): string {
  const lines = colors(p).flatMap(([k, v]) => [
    `$${k} = rgb(${bare(v)})`,
    `$${k}Alpha = ${bare(v)}`,
  ]);
  return `# ${p.meta.name} — Hyprland
# Generated by src/generators/desktop.ts from palette/. DO NOT edit by hand.
#
# Example:
#   source = ~/.config/hypr/${p.meta.slug}.conf
#   general {
#     col.active_border = $border_active
#     col.inactive_border = $border_inactive
#   }
#   decoration { shadow { color = rgba($bg0Alphaee) } }

${lines.join("\n")}
`;
}

/**
 * Waybar (GTK CSS). `@define-color` for each colour; the generated file's
 * header carries a style.css example.
 */
export function generateWaybar(p: PaletteFile): string {
  const lines = colors(p).map(([k, v]) => `@define-color ${k} ${v};`);
  return `/* ${p.meta.name} — Waybar (GTK CSS)
 * Generated by src/generators/desktop.ts from palette/. DO NOT edit by hand.
 *
 * In style.css:
 *   @import "${p.meta.slug}.css";
 *   window#waybar { background: @bg0; color: @fg1; border-bottom: 1px solid @bg3; }
 *   #workspaces button.active { color: @fg0; box-shadow: inset 0 -2px @accent; }
 *   #workspaces button.urgent { color: @urgent; }
 */

${lines.join("\n")}
`;
}

/** JSON with the palette, resolved roles and the 16 ANSI colours — for any other tool. */
export function generateJson(p: PaletteFile): string {
  const ORDER = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];
  const resolved = (group: "syntax" | "ui") =>
    Object.fromEntries(Object.keys(p.roles[group]).map((r) => [r, resolve(p, group, r)]));
  return (
    JSON.stringify(
      {
        name: p.meta.name,
        slug: p.meta.slug,
        variant: p.meta.variant,
        palette: p.palette,
        syntax: resolved("syntax"),
        ui: resolved("ui"),
        ansi: [
          ...ORDER.map((s) => resolve(p, "terminal", s)),
          ...ORDER.map((s) => ansiBright(p, s)),
        ],
      },
      null,
      2
    ) + "\n"
  );
}
